/** Запись перечня запрещённых пакетов (`bannedPackages`): имя пакета в реестре и почему его нельзя ставить. */
export interface BannedPackage {
  /** Имя пакета в реестре (`x` или `@scope/x`), без версии и диапазона. */
  readonly name: string;
  /** Почему пакет запрещён (не короче 30 видимых знаков): попадает в находку. */
  readonly reason: string;
}
