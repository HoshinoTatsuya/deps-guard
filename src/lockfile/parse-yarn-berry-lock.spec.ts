import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { InputUnreadableError } from '../input-unreadable.error';
import { TempDir } from '../testing/temp-dir';
import { ParseYarnBerryLock } from './parse-yarn-berry-lock';
import { ReadLockfile } from './read-lockfile';

const SUM = 'a'.repeat(128);
const FIXTURE = join(TempDir.FIXTURES, 'yarn-berry-project', 'protocols');

const lock = (body: string, metadata = '  version: 8\n  cacheKey: 10c0\n'): string =>
  `# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n${metadata}\n${body}`;

const refusal = (text: string): InputUnreadableError => {
  let error: unknown;
  try {
    ParseYarnBerryLock.parse(text, 'yarn.lock');
  } catch (caught) {
    error = caught;
  }
  expect(error).toBeInstanceOf(InputUnreadableError);
  return error as InputUnreadableError;
};

describe('ParseYarnBerryLock', () => {
  it('настоящий yarn.lock yarn 4.0.2: источник по протоколу каждого пакета, проекты workspace, без висячих', () => {
    const parsed = ReadLockfile.parse('yarn.lock', readFileSync(join(FIXTURE, 'yarn.lock'), 'utf8'));
    expect(parsed.kind).toBe('yarn-berry');
    expect(parsed.cacheKey).toBe('10c0');
    expect(parsed.directFieldsMerged).toBe(true);
    expect(
      Object.fromEntries(parsed.packages.map((pkg) => [`${pkg.name}@${pkg.version}`, pkg.source])),
    ).toEqual({
      'aa-lib@1.0.0': { kind: 'registry-default' },
      'bb-lib@1.0.0': { kind: 'registry-default' },
      'gen@1.0.0': { kind: 'unknown', url: 'exec:./gen.js' },
      'linked@0.0.0-use.local': { kind: 'link', url: 'linked' },
      'local-dir@1.0.0': { kind: 'directory', url: 'local-dir' },
      'localtgz@1.0.0': { kind: 'file', url: 'file:aa.tgz' },
      'portal-dir@0.0.0-use.local': { kind: 'directory', url: 'portal-dir' },
      'tarball@1.0.0': { kind: 'tarball', url: 'http://127.0.0.1:48721/aa-lib/-/aa-lib-1.0.0.tgz' },
    });
    expect(Object.keys(parsed.importers ?? {}).sort()).toEqual(['.', 'packages/ws']);
    expect(parsed.importers?.['packages/ws']).toEqual({
      'aa-lib': {
        field: 'dependencies',
        specifier: 'npm:1.0.0',
        line: expect.any(Number),
        target: 'aa-lib@npm:1.0.0',
      },
      'bb-lib': {
        field: 'dependencies',
        specifier: 'npm:^1.0.0',
        line: expect.any(Number),
        target: 'alias@npm:bb-lib@1.0.0, bb-lib@npm:^1.0.0',
      },
    });
    expect(parsed.dangling).toEqual([]);
    expect(parsed.packages.find((pkg) => pkg.name === 'aa-lib')?.integrity).toMatch(/^[0-9a-f]{128}$/);
    expect(parsed.selectors?.has('alias@npm:bb-lib@1.0.0')).toBe(true);
    expect(parsed.selectors?.has('local-dir@file:./local-dir')).toBe(true);
  });

  /**
   * Межпроектные `workspace:*`, `workspace:^`, `workspace:~` (и scope): yarn
   * пишет дескриптор диапазона в КЛЮЧ записи проекта (`lib@workspace:*,
   * lib@workspace:packages/lib`) — висячей ссылкой они не считаются. Lock-файл —
   * вывод yarn 4.18.1 (формат 10); yarn 3.4.1 (формат 6) пишет те же записи.
   */
  it('workspace:*/^/~ между проектами — не висячие ссылки (настоящий yarn.lock yarn 4.18.1)', () => {
    const text = [
      '# This file is generated by running "yarn install" inside your project.',
      '# Manual changes might be lost - proceed with caution!',
      '',
      '__metadata:',
      '  version: 10',
      '  cacheKey: 10c0',
      '',
      '"@s/lib@workspace:*, @s/lib@workspace:packages/lib":',
      '  version: 0.0.0-use.local',
      '  resolution: "@s/lib@workspace:packages/lib"',
      '  languageName: unknown',
      '  linkType: soft',
      '',
      '"app@workspace:packages/app":',
      '  version: 0.0.0-use.local',
      '  resolution: "app@workspace:packages/app"',
      '  dependencies:',
      '    "@s/lib": "workspace:*"',
      '    lib2: "workspace:^"',
      '    lib3: "workspace:~"',
      '  languageName: unknown',
      '  linkType: soft',
      '',
      '"lib2@workspace:^, lib2@workspace:packages/lib2":',
      '  version: 0.0.0-use.local',
      '  resolution: "lib2@workspace:packages/lib2"',
      '  languageName: unknown',
      '  linkType: soft',
      '',
      '"lib3@workspace:packages/lib3, lib3@workspace:~":',
      '  version: 0.0.0-use.local',
      '  resolution: "lib3@workspace:packages/lib3"',
      '  languageName: unknown',
      '  linkType: soft',
      '',
      '"root@workspace:.":',
      '  version: 0.0.0-use.local',
      '  resolution: "root@workspace:."',
      '  languageName: unknown',
      '  linkType: soft',
      '',
    ].join('\n');
    const parsed = ParseYarnBerryLock.parse(text, 'yarn.lock');
    expect(parsed.importers?.['packages/app']).toEqual({
      '@s/lib': { field: 'dependencies', specifier: 'workspace:*', line: expect.any(Number) },
      lib2: { field: 'dependencies', specifier: 'workspace:^', line: expect.any(Number) },
      lib3: { field: 'dependencies', specifier: 'workspace:~', line: expect.any(Number) },
    });
    expect(parsed.dangling).toEqual([]);
  });

  /**
   * Один проект (все протоколы: npm, алиас, catalog:, exec:, git, patch:,
   * link:, file: каталог и архив, portal:, адрес архива, workspace, пакет
   * платформы), записанный настоящим yarn 4.13.0 (формат 8), 4.14.1 (9) и
   * 4.18.1 (10): файлы отличаются только `__metadata.version`, разбор — тоже.
   */
  it('настоящие yarn.lock форматов 8, 9 и 10 (yarn 4.13.0, 4.14.1, 4.18.1) разбираются одинаково, формат записан', () => {
    const formats = join(TempDir.FIXTURES, 'yarn-berry-project', 'formats');
    const parse = (dir: string) =>
      ReadLockfile.parse('yarn.lock', readFileSync(join(formats, dir, 'yarn.lock'), 'utf8'));
    const v8 = parse('v8-yarn-4.13.0');
    const v9 = parse('v9-yarn-4.14.1');
    const v10 = parse('v10-yarn-4.18.1');
    expect([v8.berryFormat, v9.berryFormat, v10.berryFormat]).toEqual([8, 9, 10]);
    const { berryFormat: _v10, ...rest10 } = v10;
    const { berryFormat: _v9, ...rest9 } = v9;
    const { berryFormat: _v8, ...rest8 } = v8;
    expect(rest10).toEqual(rest8);
    expect(rest9).toEqual(rest8);
    expect(v10.packages).toHaveLength(13);
    expect(v10.dangling).toEqual([
      { importer: '.', name: 'bb-lib', version: 'catalog:', line: expect.any(Number) },
    ]);
    expect(
      Object.fromEntries(
        v10.packages.map((pkg) => [
          pkg.key,
          [pkg.source.kind, pkg.integrity?.slice(0, 5) ?? '-', pkg.conditions ?? '-'],
        ]),
      ),
    ).toEqual({
      'aa-lib@npm:1.0.0': ['registry-default', '10c0/', '-'],
      'alias@npm:bb-lib@1.0.0, bb-lib@npm:^1.0.0': ['registry-default', '10c0/', '-'],
      'gen@exec:./gen.js::locator=root%40workspace%3A.': ['unknown', '10c0/', '-'],
      'gitprep@git://127.0.0.1:19418/gitprep#commit=201cc55bf124f10e68ba3e30b7e8026dee079603': [
        'git',
        '10c0/',
        '-',
      ],
      'hook-a@npm:1.0.0': ['registry-default', '10c0/', '-'],
      'hook-b@npm:1.0.0': ['registry-default', '10c0/', '-'],
      'hook-b@patch:hook-b@npm%3A1.0.0#./patches/hook-b.patch::locator=root%40workspace%3A.': [
        'registry-default',
        '10c0/',
        '-',
      ],
      'linked@link:./linked::locator=root%40workspace%3A.': ['link', '-', '-'],
      'local-dir@file:./local-dir::locator=root%40workspace%3A.': ['directory', '10c0/', '-'],
      'localtgz@file:./aa.tgz::locator=root%40workspace%3A.': ['file', '10c0/', '-'],
      'plat-win@npm:1.0.0': ['registry-default', '-', 'os=win32 & cpu=x64'],
      'portal-dir@portal:./portal-dir::locator=root%40workspace%3A.': ['directory', '-', '-'],
      'tarball@http://127.0.0.1:48721/aa-lib/-/aa-lib-1.0.0.tgz': ['tarball', '10c0/', '-'],
    });
  });

  it('формат 6: диапазоны без npm:, patch: — источник исходного пакета, git — по #commit=, условия платформы', () => {
    const parsed = ParseYarnBerryLock.parse(
      lock(
        [
          '"resolve@patch:resolve@^1.1.7#~builtin<compat/resolve>":',
          '  version: 1.22.1',
          '  resolution: "resolve@patch:resolve@npm%3A1.22.1#~builtin<compat/resolve>::version=1.22.1&hash=c3c19d"',
          `  checksum: ${SUM}`,
          '',
          '"g@https://github.com/u/g.git#commit=0123456789abcdef0123456789abcdef01234567":',
          '  version: 1.0.0',
          '  resolution: "g@https://github.com/u/g.git#commit=0123456789abcdef0123456789abcdef01234567"',
          '',
          '"n@npm:0.12.1":',
          '  version: 0.12.1',
          '  resolution: "n@npm:0.12.1"',
          '  conditions: os=darwin & cpu=arm64',
          '',
          '"root@workspace:.":',
          '  version: 0.0.0-use.local',
          '  resolution: "root@workspace:."',
          '  dependencies:',
          '    css-what: 2.1',
          '',
        ].join('\n'),
        '  version: 6\n  cacheKey: 8\n',
      ),
      'yarn.lock',
    );
    expect(parsed.packages.map((pkg) => [pkg.name, pkg.source, pkg.conditions])).toEqual([
      ['resolve', { kind: 'registry-default' }, undefined],
      [
        'g',
        {
          kind: 'git',
          url: 'https://github.com/u/g.git',
          commit: '0123456789abcdef0123456789abcdef01234567',
        },
        undefined,
      ],
      ['n', { kind: 'registry-default' }, 'os=darwin & cpu=arm64'],
    ]);
    expect(parsed.cacheKey).toBe('8');
    expect(parsed.dangling).toEqual([
      { importer: '.', name: 'css-what', version: '2.1', line: expect.any(Number) },
    ]);
  });

  it.each([
    ['версия формата вне 4–10', lock('', '  version: 11\n  cacheKey: 10c0\n')],
    ['версия формата 3', lock('', '  version: 3\n  cacheKey: 10c0\n')],
    ['нет __metadata', '"a@npm:1.0.0":\n  version: 1.0.0\n  resolution: "a@npm:1.0.0"\n'],
    ['неизвестный протокол', lock('"a@weird:x":\n  version: 1.0.0\n  resolution: "a@weird:x"\n')],
    ['нет resolution', lock('"a@npm:1.0.0":\n  version: 1.0.0\n')],
    ['resolution не локатор', lock('"a@npm:1.0.0":\n  version: 1.0.0\n  resolution: "a"\n')],
    ['дескриптор без имени', lock('"@npm:1.0.0":\n  version: 1.0.0\n  resolution: "a@npm:1.0.0"\n')],
    [
      'привязка не к проекту',
      lock(
        '"a@link:./x::locator=b%40npm%3A1.0.0":\n  version: 0.0.0\n  resolution: "a@link:./x::locator=b%40npm%3A1.0.0"\n',
      ),
    ],
    ['patch: без исходного пакета', lock('"a@patch:x#p":\n  version: 1.0.0\n  resolution: "a@patch:x#p"\n')],
    [
      'checksum не строка',
      lock('"a@npm:1.0.0":\n  version: 1.0.0\n  resolution: "a@npm:1.0.0"\n  checksum: [x]\n'),
    ],
    [
      'зависимости проекта не строки',
      lock(
        '"r@workspace:.":\n  version: 0.0.0\n  resolution: "r@workspace:."\n  dependencies:\n    a: [x]\n',
      ),
    ],
    ['табуляция после «:»', lock('"a@npm:1.0.0":\n  version: 1.0.0\n  resolution:\t"a@npm:1.0.0"\n')],
    [
      'повтор ключа (yarn берёт последний)',
      lock('"a@npm:1.0.0":\n  version: 1.0.0\n  version: 2.0.0\n  resolution: "a@npm:1.0.0"\n'),
    ],
  ])('%s — отказ', (_name, text) => {
    expect(refusal(text).path).toBe('yarn.lock');
  });

  it('скаляры — строки, как у yarn (FAILSAFE): число в другой записи и true не отказ и не булево', () => {
    const parsed = ParseYarnBerryLock.parse(
      lock(
        '"r@workspace:.":\n  version: 0.0.0-use.local\n  resolution: "r@workspace:."\n  dependencies:\n    a: 1.10\n    b: true\n',
      ),
      'yarn.lock',
    );
    expect(parsed.importers?.['.']).toMatchObject({ a: { specifier: '1.10' }, b: { specifier: 'true' } });
  });

  it('заголовок «# yarn lockfile v1» — yarn 1, иначе — yarn 2+ (как решает сам yarn)', () => {
    expect(ReadLockfile.parse('yarn.lock', '# yarn lockfile v1\n\n').kind).toBe('yarn');
    expect(ReadLockfile.parse('yarn.lock', '# c\n# yarn lockfile v1\n').kind).toBe('yarn');
    expect(ReadLockfile.parse('yarn.lock', lock('')).kind).toBe('yarn-berry');
    expect(() => ReadLockfile.parse('yarn.lock', 'a: 1\n# yarn lockfile v1\n')).toThrow(InputUnreadableError);
  });

  it('диапазон дескриптора: у диапазона реестра — npm:, протокол и путь — как есть', () => {
    expect(
      ['^1.0.0', 'latest', 'npm:x@1', 'workspace:*', 'file:./x', './x', 'u/r', 'https://h/x.tgz'].map(
        (spec) => ParseYarnBerryLock.descriptorRange(spec),
      ),
    ).toEqual([
      'npm:^1.0.0',
      'npm:latest',
      'npm:x@1',
      'workspace:*',
      'file:./x',
      './x',
      'u/r',
      'https://h/x.tgz',
    ]);
  });
});
