import { InputUnreadableError } from '../input-unreadable.error';
import { ParseNpmLock } from './parse-npm-lock';
import { ParseYarnLock } from './parse-yarn-lock';

const NPM_LOCK = JSON.stringify(
  {
    name: 'p',
    lockfileVersion: 3,
    packages: {
      '': {
        name: 'p',
        workspaces: ['packages/*'],
        dependencies: { a: '1.0.0' },
        devDependencies: { hook: '^2.0.0' },
      },
      'node_modules/a': {
        version: '1.0.0',
        resolved: 'https://registry.npmjs.org/a/-/a-1.0.0.tgz',
        integrity: 'sha512-a==',
      },
      'node_modules/hook': {
        version: '2.1.0',
        resolved: 'https://registry.npmjs.org/hook/-/hook-2.1.0.tgz',
        integrity: 'sha512-h==',
        dev: true,
        hasInstallScript: true,
      },
      'node_modules/a/node_modules/g': { version: '0.1.0', resolved: 'git+ssh://git@github.com/u/g.git#abc' },
      'node_modules/a/node_modules/inner': { version: '1.0.0', inBundle: true, hasInstallScript: true },
      'node_modules/ws': { resolved: 'packages/ws', link: true },
      'packages/ws': { name: 'ws', version: '0.0.0', dependencies: { a: '1.0.0' } },
    },
  },
  null,
  2,
);

const YARN_LOCK = [
  '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
  '# yarn lockfile v1',
  '',
  '',
  '"@s/a@^1.0.0", "@s/a@^1.1.0":',
  '  version "1.2.0"',
  '  resolved "https://registry.yarnpkg.com/@s/a/-/a-1.2.0.tgz#0123"',
  '  integrity sha512-q==',
  '  dependencies:',
  '    b "^2.0.0"',
  '',
  'b@^2.0.0:',
  '  version "2.0.1"',
  '  resolved "https://registry.yarnpkg.com/b/-/b-2.0.1.tgz#abcd"',
  '',
].join('\n');

describe('ParseNpmLock', () => {
  it('v3: пакеты, вложенные, git, bundled (в дереве, источник — родитель), ссылки, проекты workspace, hasInstallScript', () => {
    const lock = ParseNpmLock.parse(NPM_LOCK, 'package-lock.json');
    expect(lock.packages.map((pkg) => [pkg.name, pkg.version, pkg.source.kind, pkg.installScript])).toEqual([
      ['a', '1.0.0', 'tarball', false],
      ['hook', '2.1.0', 'tarball', true],
      ['g', '0.1.0', 'git', false],
      ['inner', '1.0.0', 'bundled', true],
      ['ws', 'link:packages/ws', 'link', undefined],
    ]);
    expect(lock.packages[3]?.source.url).toBe('node_modules/a');
    expect(lock.dangling).toEqual([]);
    expect(lock.packages[2]?.source.commit).toBe('abc');
    expect({ ...lock.importers?.['.']?.hook }).toEqual({
      field: 'devDependencies',
      specifier: '^2.0.0',
      line: 5,
      target: 'node_modules/hook',
    });
    expect(Object.keys(lock.importers ?? {})).toEqual(['.', 'packages/ws']);
    expect(lock.packages[0]?.line).toBe(17);
  });

  it('прямая зависимость без записи node_modules/<имя> — висячая ссылка; у проекта workspace ищется и в корне', () => {
    const lock = ParseNpmLock.parse(
      JSON.stringify({
        lockfileVersion: 3,
        packages: {
          '': {
            workspaces: ['packages/*'],
            dependencies: { here: '1.0.0', gone: '1.0.0', constructor: '1.0.0' },
          },
          'node_modules/here': { version: '1.0.0', resolved: 'https://r/here.tgz', integrity: 'sha512-x' },
          'packages/w': { dependencies: { here: '1.0.0', own: '1.0.0' } },
          'packages/w/node_modules/own': {
            version: '1.0.0',
            resolved: 'https://r/own.tgz',
            integrity: 'sha512-y',
          },
        },
      }),
      'package-lock.json',
    );
    expect(Object.keys(lock.importers ?? {})).toEqual(['.', 'packages/w']);
    expect(lock.dangling?.map((entry) => [entry.importer, entry.name])).toEqual([
      ['.', 'gone'],
      ['.', 'constructor'],
    ]);
  });

  /**
   * `file:`-зависимость npm 7+ записывает ДВАЖДЫ: ссылкой `node_modules/<имя>`
   * и записью по пути цели (`vendor/lib`, `../shared`) — той же формы, что
   * проект workspace. Проект — только каталог под шаблонами `workspaces`
   * корневой записи; цель ссылки проектом не считалась бы: её package.json
   * читался бы как проект репозитория (а `../shared` — за пределами корня).
   * Lock-файл — вывод npm 11.19.1 (`npm install --offline`).
   */
  it('цель file:-зависимости — не проект workspace; проекты — по шаблонам workspaces корня', () => {
    const lock = ParseNpmLock.parse(
      JSON.stringify(
        {
          name: 'root',
          version: '1.0.0',
          lockfileVersion: 3,
          requires: true,
          packages: {
            '': {
              name: 'root',
              version: '1.0.0',
              workspaces: ['packages/*'],
              dependencies: { lib: 'file:./vendor/lib', shared: 'file:../shared' },
            },
            '../shared': { version: '1.0.0' },
            'node_modules/a': { resolved: 'packages/a', link: true },
            'node_modules/lib': { resolved: 'vendor/lib', link: true },
            'node_modules/shared': { resolved: '../shared', link: true },
            'packages/a': { version: '1.0.0' },
            'vendor/lib': { version: '1.0.0', dependencies: { a: '*' } },
          },
        },
        null,
        2,
      ),
      'package-lock.json',
    );
    expect(Object.keys(lock.importers ?? {})).toEqual(['.', 'packages/a']);
    expect(lock.packages.map((pkg) => [pkg.name, pkg.source.kind, pkg.source.url])).toEqual([
      ['a', 'link', 'packages/a'],
      ['lib', 'link', 'vendor/lib'],
      ['shared', 'link', '../shared'],
    ]);
    expect(lock.dangling).toEqual([]);
  });

  it('корень без workspaces — ни одна запись вне node_modules не проект', () => {
    const lock = ParseNpmLock.parse(
      JSON.stringify({
        lockfileVersion: 3,
        packages: {
          '': { dependencies: { lib: 'file:./vendor/lib' } },
          'node_modules/lib': { resolved: 'vendor/lib', link: true },
          'vendor/lib': { version: '1.0.0', dependencies: { ms: '^2.0.0' } },
        },
      }),
      'package-lock.json',
    );
    expect(Object.keys(lock.importers ?? {})).toEqual(['.']);
  });

  it.each([1, 4, '3', undefined])('lockfileVersion %p — отказ с версией в причине', (version) => {
    expect(() =>
      ParseNpmLock.parse(JSON.stringify({ lockfileVersion: version, packages: {} }), 'package-lock.json'),
    ).toThrow(`lockfileVersion ${String(version)} не поддерживается`);
  });

  it.each([2, 3])('lockfileVersion %d — разбирается', (version) => {
    expect(
      ParseNpmLock.parse(JSON.stringify({ lockfileVersion: version, packages: {} }), 'x.json').kind,
    ).toBe('npm');
  });

  it.each([
    ['v1', JSON.stringify({ lockfileVersion: 1, dependencies: {} })],
    ['не JSON', '{'],
    ['без packages', JSON.stringify({ lockfileVersion: 3 })],
    ['packages — массив', JSON.stringify({ lockfileVersion: 3, packages: [] })],
    ['пакет без version', JSON.stringify({ lockfileVersion: 3, packages: { 'node_modules/a': {} } })],
  ])('%s — InputUnreadableError', (_name, text) => {
    expect(() => ParseNpmLock.parse(text, 'package-lock.json')).toThrow(InputUnreadableError);
  });
});

describe('ParseYarnLock', () => {
  it('v1: селекторы, scope, адрес без хэша, integrity', () => {
    const lock = ParseYarnLock.parse(YARN_LOCK, 'yarn.lock');
    expect(
      lock.packages.map((pkg) => [pkg.name, pkg.version, pkg.source.url, pkg.integrity, pkg.line]),
    ).toEqual([
      ['@s/a', '1.2.0', 'https://registry.yarnpkg.com/@s/a/-/a-1.2.0.tgz', 'sha512-q==', 5],
      ['b', '2.0.1', 'https://registry.yarnpkg.com/b/-/b-2.0.1.tgz', undefined, 12],
    ]);
    expect([...(lock.selectors ?? [])]).toEqual(['@s/a@^1.0.0', '@s/a@^1.1.0', 'b@^2.0.0']);
    expect(lock.importers).toBeUndefined();
  });

  it('npm:-алиас — настоящее имя; file: и link: без resolved — каталог и ссылка, а не реестр', () => {
    const lock = ParseYarnLock.parse(
      [
        '# yarn lockfile v1',
        '',
        '"lodash@npm:lodahs@1.0.0":',
        '  version "1.0.0"',
        '  resolved "https://registry.yarnpkg.com/lodahs/-/lodahs-1.0.0.tgz#abc"',
        '  integrity sha512-q==',
        '',
        '"loc@file:./local":',
        '  version "1.0.0"',
        '',
        '"l@link:./l":',
        '  version "0.0.0"',
        '',
        '"r@^1.0.0":',
        '  version "1.0.0"',
        '',
      ].join('\n'),
      'yarn.lock',
    );
    expect(lock.packages.map((pkg) => [pkg.name, pkg.source.kind, pkg.source.url])).toEqual([
      ['lodahs', 'tarball', 'https://registry.yarnpkg.com/lodahs/-/lodahs-1.0.0.tgz'],
      ['loc', 'directory', 'file:./local'],
      ['l', 'link', 'l'],
      ['r', 'registry-default', undefined],
    ]);
    expect(lock.selectors?.has('lodash@npm:lodahs@1.0.0')).toBe(true);
  });

  it.each([
    ['yarn 2+', '__metadata:\n  version: 6\n'],
    ['без заголовка', 'a@1:\n  version "1"\n'],
    ['запись без version', '# yarn lockfile v1\na@1:\n  resolved "x"\n'],
    ['строка вне записи', '# yarn lockfile v1\n  version "1"\n'],
    ['мусор', '# yarn lockfile v1\na@1:\n  version "1"\n\tbad\n'],
    ['селекторы разных пакетов в одной записи', '# yarn lockfile v1\n"a@1", "b@npm:c@1":\n  version "1"\n'],
    [
      'повтор поля',
      '# yarn lockfile v1\na@1:\n  version "1"\n  resolved "https://r/a.tgz"\n  resolved "https://e/a.tgz"\n',
    ],
  ])('%s — InputUnreadableError', (_name, text) => {
    expect(() => ParseYarnLock.parse(text, 'yarn.lock')).toThrow(InputUnreadableError);
  });
});
