/**
 * Вердикт находки:
 * - `violation` — нарушение правила;
 * - `stale` — запись допуска, которой больше ничего не соответствует;
 * - `unverified` — не проверено (нет данных); это НЕ зелёный результат;
 * - `broken` — не смог прочитать вход (lock-файл, настройку, базовую линию);
 * - `matured` — допуск свежести больше не нужен: версия созрела сама. Это
 *   предупреждение, а не нарушение (код выхода 0): иначе ветка без единого
 *   коммита краснела бы через `minAgeDays` дней на законном состоянии.
 */
export type Verdict = 'violation' | 'stale' | 'unverified' | 'broken' | 'matured';
